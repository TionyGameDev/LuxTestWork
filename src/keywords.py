"""Базовый разметчик по ключевым словам: работает без ключа и служит точкой сравнения для LLM."""

# (тема, тон, части слов в нижнем регистре)
RULES = [
    ("noise", "neg", ["шум", "гуд", "громк", "звук мотора", "дрел", "самолёт", "самолет"]),
    ("delivery", "neg", ["доставк", "ждал", "курьер", "дней вместо"]),
    ("delivery", "pos", ["приехала за", "приехал за", "быстрая доставка"]),
    ("durability", "neg", ["сломал", "перестал", "не включ", "потрескал", "протекает", "запах", "скрип", "греет то"]),
    ("packaging", "neg", ["помят", "вскрыт", "порван", "упаковк"]),
    ("support", "neg", ["поддержк", "вернули деньги", "отказались", "шаблон"]),
    ("price", "neg", ["завышен", "дорог"]),
    ("price", "pos", ["цена приятн", "для своей цены", "за такой объём"]),
    ("performance", "pos", ["чисто убирает", "готовит", "вкусн", "отпаривает", "блестят", "отличн", "работает нормально", "сочн", "фри", "греется за"]),
    ("performance", "neg", ["застрял", "застревает", "слабый", "плохо"]),
    ("usability", "pos", ["удобн", "легко моется", "моется легко", "возвращается на базу", "подходит"]),
    ("usability", "neg", ["тяжёл", "тяжел", "шнур", "мыть сложно", "теряет связь"]),
]


def classify_keywords(reviews):
    labels = {}
    for r in reviews:
        text = r.text.lower()
        found = {}
        for topic, sentiment, stems in RULES:
            if any(s in text for s in stems):
                found.setdefault(topic, sentiment)
        if not found:
            found["other"] = "pos" if r.rating >= 4 else "neu"
        labels[r.id] = [[t, s] for t, s in found.items()]
    return labels
